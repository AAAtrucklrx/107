"""隐私敏感模式的唯一来源（脱敏器 / 个人问题识别 / URL 参数守卫共用）。

历史（2026-09-15 定位）：学号正则在三处各抄了一份，名单互不一致——
`chat/privacy.py` 只认 `PB`，`evidence/privacy.py` 与 `evidence/url_security.py`
认 `(?:PB|SA|BA|BE|MG|UG)`。后果：

1. 按 `PB` 判定的「个人问题识别」认不出研究生学号，研究生用 `SA`/`BA` 自报身份
   问成绩时不会被要求登录、也不会被降级为本地处理（`chat/manager.py:74-82`）；
2. `SB`（单独考试入学硕士、退役大学生士兵计划）与 `SG`（MBA/MPA）谁都不认；
3. `MG`/`UG` 是无出处的猜测（见 `d5431db` 初始提交），已移除。

另一处更隐蔽的缺陷：边界曾写作 `\\b`。Python 3 的 `\\w` 含汉字，
「我的学号是PB25111691」里汉字与 `P` 之间**没有词边界**，整条正则失效——
而不带空格恰恰是中文最自然的写法，学号会被原样送往外部搜索。

本模块提供唯一名单与唯一正则，上述三处一律从这里导入，避免再次漂移。
"""

from __future__ import annotations

import re

# 中科大学号：10 位 = 前缀(2) + 入学学年(2) + 专业代码(2) + 序号(4)。
# 例：PB25111691 = PB + 25(2025 学年) + 11(专业代码 011 计算机科学与技术) + 1691。
# 前缀含义由用户 2026-09-15 提供（学历教育研究生双证 / 非学历教育单证 / 代培 / 留学生与港澳台）。
STUDENT_ID_PREFIXES: tuple[str, ...] = (
    "PB",  # 普通教育本科生（1997 学年及以后入学）
    # ── 学历教育研究生（双证）──
    "BA",  # 全日制学术博士
    "BE",  # 全日制工程博士
    "BZ",  # 全日制直博生
    "SA",  # 全日制硕士生
    "SB",  # 单独考试入学硕士生、全日制退役大学生士兵计划
    "SM",  # 全日制 MBA / MPA / 工程管理硕士
    "SF",  # 非全日制硕士
    "SG",  # 历史前缀：MBA/MPA 专业学位（2014 年公开问答；现行名单记作 SM，保留兼容）
    # ── 非学历教育研究生（单证）──
    "BJ",  # 在职攻读同等学力博士
    # ── 代培研究生 ──
    "BC",  # 代培博士生
    "SC",  # 代培硕士生
    # ── 留学生与港澳台研究生 ──
    "BL",  # 博士外国留学生
    "SL",  # 硕士外国留学生
    "CB",  # 港澳台博士生
    "CS",  # 港澳台硕士生
)

# 边界不得用 \b（汉字属于 \w，中文紧邻时 \b 不成立）。
# 前面不是 ASCII 字母数字（中文可紧邻），后面不是数字（避免截断更长的数字串）。
STUDENT_ID_PATTERN = r"(?<![A-Za-z0-9])(?:%s)\d{8}(?!\d)" % "|".join(STUDENT_ID_PREFIXES)

# 已编译实例：脱敏（sub）与判定（search）共用，避免各处重复 compile 与漂移。
STUDENT_ID_RE = re.compile(STUDENT_ID_PATTERN, re.IGNORECASE)
